import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { buildApk } from '../apk/fixture.ts';
import { dataDir } from '../config.ts';
import { emptyResult, type Provider, type ProviderResult, type ResolveContext } from './types.ts';

/**
 * Offline source used for demos and tests: builds a genuine, signed-but-fake APK
 * with the requested package name and version, so the download → verify →
 * library flow can be exercised with no network at all.
 *
 * Files from here are marked as fixtures everywhere they appear. They are not
 * usable apps, and their signing certificate is PatchPilot's test key rather than
 * any real developer's.
 */

export class DemoProvider implements Provider {
  readonly id = 'demo';
  readonly label = 'Offline demo fixture';
  readonly description = 'Generates a stand-in APK locally so the whole flow can be tried without network.';
  readonly homepage = 'https://github.com/mob5824m-wq/PatchPilot';
  readonly kind = 'file' as const;
  readonly notes = [
    'Not a real app: the APK is generated by PatchPilot for demonstration and testing.',
    "Signed with PatchPilot's test certificate, so verification will flag the signature deliberately.",
  ];

  async resolve(context: ResolveContext): Promise<ProviderResult> {
    if (!context.versionName) {
      return emptyResult('The demo source needs a concrete version to imitate.');
    }

    const dir = join(dataDir, 'demo');
    await mkdir(dir, { recursive: true });
    const fileName = `${context.packageName}-${context.versionName}-DEMO.apk`;
    const path = join(dir, fileName);

    const codes = context.versionCodes ? Object.values(context.versionCodes) : [];
    const bytes = buildApk({
      packageName: context.packageName,
      versionName: context.versionName,
      versionCode: codes[0] ?? 1,
      label: context.appName,
      paddingBytes: 1024 * 64,
    });
    await writeFile(path, bytes);

    context.log('warn', `Offline demo fixture generated at ${path} — this is not a real app.`);
    return {
      files: [{ url: `file://${path}`, localPath: path, label: `Demo fixture for ${context.versionName}` }],
      pages: [],
      detail: 'Generated an offline demo fixture matching the requested package and version.',
    };
  }
}
